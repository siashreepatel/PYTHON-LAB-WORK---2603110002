# IT8 - CERTIFY THE MACHINE

class SpecViolation(Exception):
    """Raised when a part is outside specification."""
    pass


class Machine:

    def __init__(self, name):
        self.name = name
        self.total = 0
        self.accept = 0
        self.rework = 0
        self.scrap = 0

    def operate(self, diameter):

        if not isinstance(diameter, (int, float)) or isinstance(diameter, bool):
            raise TypeError("Diameter must be numeric")

        if not 0 < diameter < 100:
            raise ValueError("Invalid diameter")

        self.total += 1

        if 24.95 <= diameter <= 25.05:
            self.accept += 1
            return "ACCEPT"

        elif 24.90 <= diameter <= 25.10:
            self.rework += 1
            return "REWORK"

        else:
            self.scrap += 1
            raise SpecViolation(
                f"{diameter} mm is outside specification"
            )

    def status(self):
        return {
            "Machine": self.name,
            "Total": self.total,
            "ACCEPT": self.accept,
            "REWORK": self.rework,
            "SCRAP": self.scrap
        }


# Main program

machine = Machine("Machine A")

jobs = [25.00, 24.98, 25.15, 25.02, 24.92, 25.20]

print("MACHINE PRODUCTION REPORT")
print("-------------------------")

for i, diameter in enumerate(jobs, 1):

    try:
        result = machine.operate(diameter)
        print(f"Job {i}: {result}")

    except SpecViolation as error:
        print(f"Job {i}: REJECTED - {error}")

    except (ValueError, TypeError) as error:
        print(f"Job {i}: INVALID - {error}")


print("\nFINAL MACHINE STATUS")
print(machine.status())


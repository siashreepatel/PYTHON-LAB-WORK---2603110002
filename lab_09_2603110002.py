def parse_line(line):
    """Parse and validate a production log line."""

    if not isinstance(line, str):
        raise TypeError("Input must be a string")

    fields = line.split(",")

    if len(fields) != 3:
        raise ValueError("Expected 3 fields")

    code = fields[0].strip()
    diameter_text = fields[1].strip()
    shift = fields[2].strip().upper()

    if not code.startswith("P") or not code[1:].isdigit():
        raise ValueError("Invalid part code")

    if not diameter_text:
        raise ValueError("Missing diameter")

    diameter = float(diameter_text)

    if not 0 < diameter < 100:
        raise ValueError("Diameter outside valid range")

    if shift not in ("DAY", "NIGHT"):
        raise ValueError("Invalid shift")

    return code, diameter, shift



# IT8 - THE PARTS CATALOGUE

def inspect(dia):
    """Return the quality category of a diameter."""
    if 24.95 <= dia <= 25.05:
        return "ACCEPT"
    elif 24.90 <= dia <= 25.10:
        return "REWORK"
    else:
        return "SCRAP"


def lookup(catalogue, code):
    """Find a part diameter or return a default message."""
    return catalogue.get(code, "Part not found")


def scrap_codes(catalogue):
    """Return a set of part codes outside specification."""
    return {
        code for code, dia in catalogue.items()
        if inspect(dia) == "SCRAP"
    }


# CREATE CATALOGUE

log_lines = [
    "P101,24.98,DAY",
    "P102,25.03,NIGHT",
    "P103,24.85,DAY",
    "P104,25.01,NIGHT",
    "P105,25.15,DAY",
    "P106,24.97,NIGHT"
]

catalogue = {}

for line in log_lines:
    fields = line.split(",")

    code = fields[0].strip()
    dia = float(fields[1].strip())

    catalogue[code] = dia



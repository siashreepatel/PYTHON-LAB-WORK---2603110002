# IT12 - THREE JIGS

def inspect(dia):
    """Check diameter and return its quality bin."""
    if 24.95 <= dia <= 25.05:
        return "ACCEPT"
    elif 24.90 <= dia <= 25.10:
        return "REWORK"
    else:
        return "SCRAP"


def tally(labels):
    """Count ACCEPT, REWORK and SCRAP labels."""
    counts = {
        "ACCEPT": 0,
        "REWORK": 0,
        "SCRAP": 0
    }

    for label in labels:
        counts[label] += 1

    return counts


def report(shift, counts):
    """Create a formatted shift report."""
    return (
        f"Shift: {shift} | "
        f"ACCEPT: {counts['ACCEPT']} | "
        f"REWORK: {counts['REWORK']} | "
        f"SCRAP: {counts['SCRAP']}"
    )



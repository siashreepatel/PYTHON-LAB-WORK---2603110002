# IT10 - THE GUARDED MACHINE

class Machine:

    def __init__(self, name):
        self.name = name
        self.__parts = 0
        self.__accept = 0
        self.__rework = 0
        self.__scrap = 0

    def operate(self, diameter):

        # Validate input
        if not isinstance(diameter, (int, float)):
            print("Error: Diameter must be a number.")
            return

        if not 0 < diameter < 100:
            print("Error: Invalid operating command.")
            return

        self.__parts += 1

        if 24.95 <= diameter <= 25.05:
            self.__accept += 1
            print("ACCEPT")

        elif 24.90 <= diameter <= 25.10:
            self.__rework += 1
            print("REWORK")

        else:
            self.__scrap += 1
            print("SCRAP")

    def status(self):
        return {
            "Machine": self.name,
            "Total Parts": self.__parts,
            "ACCEPT": self.__accept,
            "REWORK": self.__rework,
            "SCRAP": self.__scrap
        }


# Create machine

m1 = Machine("Machine A")

# Operate machine

m1.operate(25.00)
m1.operate(24.92)
m1.operate(25.15)

# Invalid commands

m1.operate(-5)
m1.operate("hello")

# Display status

print("\nMACHINE STATUS")
print(m1.status())


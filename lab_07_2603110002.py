import random

class Machine:

    def __init__(self, name):
        self.name = name
        self.__total = 0
        self.__accept = 0
        self.__rework = 0
        self.__scrap = 0

    def operate(self, diameter):

        if not isinstance(diameter, (int, float)):
            print("Invalid diameter")
            return

        if not 0 < diameter < 100:
            print("Invalid operating command")
            return

        self.__total += 1

        if 24.95 <= diameter <= 25.05:
            self.__accept += 1
            result = "ACCEPT"

        elif 24.90 <= diameter <= 25.10:
            self.__rework += 1
            result = "REWORK"

        else:
            self.__scrap += 1
            result = "SCRAP"

        print(f"{diameter:.2f} mm - {result}")

    def status(self):

        return {
            "Machine": self.name,
            "Total": self.__total,
            "ACCEPT": self.__accept,
            "REWORK": self.__rework,
            "SCRAP": self.__scrap
        }


# Create machine

machine = Machine("Production Machine")

# Generate and process 10 jobs

print("BATCH PRODUCTION")
print("----------------")

for i in range(10):

    diameter = random.uniform(24.85, 25.15)

    print(f"Job {i+1}: ", end="")
    machine.operate(diameter)

# Shift report

print("\nSHIFT REPORT")
print(machine.status())


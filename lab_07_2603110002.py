class Machine:

    def __init__(self, name):
        self.name = name
        self.__total = 0
        self.__accept = 0
        self.__rework = 0
        self.__scrap = 0
        self.__busy = False

    def is_free(self):
        """Check whether the machine is available."""
        return not self.__busy

    def operate(self, diameter):
        """Process a part and update machine counters."""

        if not self.is_free():
            print("Machine is busy")
            return

        if not isinstance(diameter, (int, float)):
            print("Invalid diameter")
            return

        if not 0 < diameter < 100:
            print("Invalid operating command")
            return

        self.__busy = True
        self.__total += 1

        if 24.95 <= diameter <= 25.05:
            self.__accept += 1
            result = "ACCEPT"

        elif 24.90 <= diameter <= 25.10:
            self.__rework += 1
            result = "REWORK"

        else:
            self.__scrap += 1
            result = "SCRAP"

        print(f"{self.name}: {diameter:.2f} - {result}")

        self.__busy = False

    def status(self):
        """Return machine production statistics."""

        return {
            "Machine": self.name,
            "Total": self.__total,
            "ACCEPT": self.__accept,
            "REWORK": self.__rework,
            "SCRAP": self.__scrap
        }
import random

consecutive_accepts = 0
attempts = 0
max_attempts = 500

print("PRECISION - RUN UNTIL GOOD")
print("--------------------------")

while consecutive_accepts < 5 and attempts < max_attempts:

    diameter = random.uniform(24.90, 25.10)
    attempts += 1

    if 24.95 <= diameter <= 25.05:
        consecutive_accepts += 1
        print(f"Attempt {attempts}: {diameter:.2f} - ACCEPT")

    else:
        consecutive_accepts = 0
        print(f"Attempt {attempts}: {diameter:.2f} - NOT ACCEPT")

if consecutive_accepts == 5:
    print("\nFive consecutive ACCEPTs achieved!")

else:
    print("\nSafety limit reached!")

print("Total Attempts:", attempts)
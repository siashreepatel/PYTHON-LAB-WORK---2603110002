day_lines = [
    "P101, 24.98, DAY",
    "P102, 25.12, DAY",
    "P103, 24.92, DAY",
    "P104, 25.01, DAY",
    "P105, 25.15, DAY"
]

night_lines = [
    "P101, 25.12, NIGHT",
    "P102, 25.03, NIGHT",
    "P106, 24.88, NIGHT",
    "P104, 25.01, NIGHT",
    "P107, 25.14, NIGHT"
]

day_scrap = set()
night_scrap = set()

day_accept = 0
night_accept = 0

# DAY SHIFT
for line in day_lines:

    fields = line.split(",")

    part_code = fields[0].strip()
    diameter = float(fields[1].strip())

    if 24.95 <= diameter <= 25.05:
        day_accept += 1

    elif diameter < 24.90 or diameter > 25.10:
        day_scrap.add(part_code)

# NIGHT SHIFT
for line in night_lines:

    fields = line.split(",")

    part_code = fields[0].strip()
    diameter = float(fields[1].strip())

    if 24.95 <= diameter <= 25.05:
        night_accept += 1

    elif diameter < 24.90 or diameter > 25.10:
        night_scrap.add(part_code)

# ACCEPT RATES
day_rate = (day_accept / len(day_lines)) * 100
night_rate = (night_accept / len(night_lines)) * 100

print("SHIFT COMPARISON REPORT")
print("-----------------------")

print("Day Accept Rate:", day_rate, "%")
print("Night Accept Rate:", night_rate, "%")

# SET COMPARISON
print("\nCOMMON SCRAP CODES:")
print(day_scrap & night_scrap)

print("\nDAY ONLY SCRAP CODES:")
print(day_scrap - night_scrap)

print("\nNIGHT ONLY SCRAP CODES:")
print(night_scrap - day_scrap)
# IT10 - THE FULL PIPELINE

import os
import csv

os.makedirs("data", exist_ok=True)

# Parse function
def parse_line(line):
    """Parse and validate a production record."""

    fields = line.split(",")

    if len(fields) != 3:
        raise ValueError("Expected three fields")

    code = fields[0].strip()
    diameter = float(fields[1].strip())
    shift = fields[2].strip().upper()

    if not code.startswith("P") or not code[1:].isdigit():
        raise ValueError("Invalid part code")

    if not 0 < diameter < 100:
        raise ValueError("Invalid diameter")

    if shift not in ("DAY", "NIGHT"):
        raise ValueError("Invalid shift")

    return code, diameter, shift


# Read input file
accepted = []
rejects = []

with open("data/shift_log.txt", "r") as file:

    for line in file:

        line = line.strip()

        if not line:
            continue

        try:
            code, dia, shift = parse_line(line)

            if 24.95 <= dia <= 25.05:
                result = "ACCEPT"

            elif 24.90 <= dia <= 25.10:
                result = "REWORK"

            else:
                result = "SCRAP"

            accepted.append((code, dia, shift, result))

        except ValueError as error:
            rejects.append((line, str(error)))

        except TypeError as error:
            rejects.append((line, str(error)))


# Calculate report
total = len(accepted)

accept_count = sum(1 for x in accepted if x[3] == "ACCEPT")
rework_count = sum(1 for x in accepted if x[3] == "REWORK")
scrap_count = sum(1 for x in accepted if x[3] == "SCRAP")

if total > 0:
    average = sum(x[1] for x in accepted) / total
else:
    average = 0


# Write human-readable report
with open("data/report.txt", "w") as file:

    file.write("PRODUCTION SHIFT REPORT\n")
    file.write("=" * 65 + "\n")

    file.write(
        f"{'CODE':<12}{'DIAMETER':<15}"
        f"{'SHIFT':<12}{'RESULT':<12}\n"
    )

    file.write("-" * 65 + "\n")

    for code, dia, shift, result in accepted:
        file.write(
            f"{code:<12}{dia:<15.2f}"
            f"{shift:<12}{result:<12}\n"
        )

    file.write("\nSUMMARY\n")
    file.write(f"Total Valid Records: {total}\n")
    file.write(f"ACCEPT: {accept_count}\n")
    file.write(f"REWORK: {rework_count}\n")
    file.write(f"SCRAP: {scrap_count}\n")
    file.write(f"Average Diameter: {average:.2f}\n")
    file.write(f"Rejected Records: {len(rejects)}\n")


# Write rejected records into CSV
with open("data/rejects.csv", "w", newline="") as file:

    writer = csv.writer(file)

    writer.writerow(["Bad Line", "Reason"])

    for line, reason in rejects:
        writer.writerow([line, reason])


# Display result
print("FULL PIPELINE COMPLETED")

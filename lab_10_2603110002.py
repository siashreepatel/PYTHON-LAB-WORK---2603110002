import re


def parse_line(line):
    """Parse and validate production records."""

    pattern = (
        r"\s*(P\d+)\s*,\s*"
        r"(\d+(?:\.\d+)?)\s*,\s*"
        r"(DAY|NIGHT)\s*"
    )

    match = re.fullmatch(pattern, line, re.IGNORECASE)

    if not match:
        raise ValueError("Invalid log format")

    code, diameter, shift = match.groups()

    diameter = float(diameter)

    if not 0 < diameter < 100:
        raise ValueError("Invalid diameter")

    return code.upper(), diameter, shift.upper()


def inspect(diameter):
    """Classify a part according to its diameter."""

    if 24.95 <= diameter <= 25.05:
        return "ACCEPT"

    elif 24.90 <= diameter <= 25.10:
        return "REWORK"

    else:
        return "SCRAP"


def process_file(filename):
    """Process one file and return its report data."""

    accepted = []
    rejects = []

    with open(filename, "r") as file:

        for line in file:

            line = line.strip()

            if not line:
                continue

            try:
                code, dia, shift = parse_line(line)

                result = inspect(dia)

                accepted.append(
                    (code, dia, shift, result)
                )

            except (ValueError, TypeError) as error:

                rejects.append((line, str(error)))

    return accepted, rejects
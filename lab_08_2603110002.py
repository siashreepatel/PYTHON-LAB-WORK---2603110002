class Machine:

    def __init__(self, name):
        self.name = name
        self.__total = 0
        self.__accept = 0
        self.__rework = 0
        self.__scrap = 0
        self.busy = False

    def is_free(self):
        """Check machine availability."""
        return not self.busy

    def operate(self, diameter):
        """Process a part and update counters."""

        if self.busy:
            print("Machine is busy")
            return

        if not isinstance(diameter, (int, float)) or isinstance(diameter, bool):
            print("Invalid diameter")
            return

        if not 0 < diameter < 100:
            print("Invalid command")
            return

        self.busy = True
        self.__total += 1

        if 24.95 <= diameter <= 25.05:
            self.__accept += 1
            result = "ACCEPT"

        elif 24.90 <= diameter <= 25.10:
            self.__rework += 1
            result = "REWORK"

        else:
            self.__scrap += 1
            result = "SCRAP"

        print(f"{self.name}: {diameter:.2f} - {result}")

        self.busy = False

    def status(self):
        """Return machine production statistics."""
        return {
            "Machine": self.name,
            "Total": self.__total,
            "ACCEPT": self.__accept,
            "REWORK": self.__rework,
            "SCRAP": self.__scrap
        }

